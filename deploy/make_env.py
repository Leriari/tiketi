"""
Build deploy/.env.production for the hosted demo, on your own machine.

    venv\\Scripts\\python deploy\\make_env.py --ip <your server's public IP>

- Generates fresh production secrets (SECRET_KEY, the ticket-credential
  encryption key, the database password) — never reuse local dev ones.
- Copies your M-Pesa sandbox, Firebase and Base Sepolia settings from your
  local .env, so you don't retype them.
- Creates three demo phone numbers with fixed codes (phone login has no SMS
  on the free deployment) and prints them for you to share.

The output file holds secrets: it's git-ignored, and you copy it to the
server yourself (scp). Re-running refuses to overwrite it unless --force,
since changing CREDENTIAL_ENCRYPTION_KEY on a live server makes existing
tickets' QR codes unreadable.
"""
import argparse
import secrets
import sys
from pathlib import Path

from cryptography.fernet import Fernet
from dotenv import dotenv_values

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / ".env.production"
FIREBASE_SITE = "https://tiketi-6e9fd.web.app,https://tiketi-6e9fd.firebaseapp.com"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ip", required=True, help="the server's public IPv4 address")
    parser.add_argument("--force", action="store_true", help="overwrite an existing .env.production")
    args = parser.parse_args()

    parts = args.ip.strip().split(".")
    if len(parts) != 4 or not all(p.isdigit() and 0 <= int(p) <= 255 for p in parts):
        sys.exit(f"'{args.ip}' isn't an IPv4 address")
    if OUT.exists() and not args.force:
        sys.exit(f"{OUT} already exists — pass --force to replace it (this changes every secret).")

    local = dotenv_values(ROOT / ".env")
    api_domain = "-".join(parts) + ".sslip.io"
    db_password = secrets.token_urlsafe(24)
    demo = {f"0700000{i:03d}": f"{secrets.randbelow(900000) + 100000}" for i in (101, 102, 103)}

    def keep(key, default=""):
        return local.get(key) or default

    values = [
        ("# Generated by deploy/make_env.py — contains secrets, never commit.", None),
        ("APP_ENV", "production"),
        ("DEBUG", "false"),
        ("SECRET_KEY", secrets.token_urlsafe(48)),
        ("CREDENTIAL_ENCRYPTION_KEY", Fernet.generate_key().decode()),
        ("", None),
        ("# Database & Redis (containers in docker-compose.prod.yml)", None),
        ("POSTGRES_PASSWORD", db_password),
        ("DATABASE_URL", f"postgresql://tiketi:{db_password}@db:5432/tiketi"),
        ("REDIS_URL", "redis://redis:6379/0"),
        ("", None),
        ("# Public address of the API (free HTTPS hostname for the server's IP)", None),
        ("API_DOMAIN", api_domain),
        ("CORS_ORIGINS", FIREBASE_SITE),
        ("", None),
        ("# M-Pesa — Daraja SANDBOX (no real money moves)", None),
        ("MPESA_ENV", "sandbox"),
        ("MPESA_CONSUMER_KEY", keep("MPESA_CONSUMER_KEY")),
        ("MPESA_CONSUMER_SECRET", keep("MPESA_CONSUMER_SECRET")),
        ("MPESA_SHORTCODE", keep("MPESA_SHORTCODE", "174379")),
        ("MPESA_PASSKEY", keep("MPESA_PASSKEY")),
        ("MPESA_CALLBACK_URL", f"https://{api_domain}/api/v1/payments/mpesa/callback"),
        ("# The 'Simulate M-Pesa success' button, for testers whose phones can't", None),
        ("# receive sandbox prompts. Sandbox only — turn off for anything real.", None),
        ("ALLOW_SIMULATED_PAYMENTS", "true"),
        ("", None),
        ("# Login: Google via Firebase; no SMS, so phone codes only for demo numbers", None),
        ("FIREBASE_PROJECT_ID", keep("FIREBASE_PROJECT_ID")),
        ("FIREBASE_API_KEY", keep("FIREBASE_API_KEY")),
        ("FIREBASE_AUTH_DOMAIN", keep("FIREBASE_AUTH_DOMAIN")),
        ("FIREBASE_APP_ID", keep("FIREBASE_APP_ID")),
        ("FIREBASE_PHONE_AUTH", "false"),
        ("OTP_DELIVERY_CHANNEL", "disabled"),
        ("GOOGLE_PHONE_CONFIRMATION", "unverified"),
        ("DEMO_PHONE_CODES", ",".join(f"{p}:{c}" for p, c in demo.items())),
        ("", None),
        ("# Blockchain — Base Sepolia testnet", None),
        ("BLOCKCHAIN_RPC_URL", keep("BLOCKCHAIN_RPC_URL")),
        ("NFT_CONTRACT_ADDRESS", keep("NFT_CONTRACT_ADDRESS")),
        ("MINTER_PRIVATE_KEY", keep("MINTER_PRIVATE_KEY")),
        ("", None),
        ("# Receipt emails over SMTP — Gmail: smtp.gmail.com with an app password", None),
        ("# (DEPLOY.md). Leave SMTP_PASSWORD empty and no email is sent.", None),
        ("SMTP_HOST", keep("SMTP_HOST", "smtp.gmail.com")),
        ("SMTP_PORT", keep("SMTP_PORT", "587")),
        ("SMTP_USERNAME", keep("SMTP_USERNAME")),
        ("SMTP_PASSWORD", keep("SMTP_PASSWORD")),
        ("SITE_URL", FIREBASE_SITE.split(",")[0]),
        ("", None),
        ("# Card payments — Paystack test mode (DEPLOY.md). Leave empty for M-Pesa only.", None),
        ("PAYSTACK_SECRET_KEY", keep("PAYSTACK_SECRET_KEY")),
    ]
    lines = [k if v is None else f"{k}={v}" for k, v in values]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    missing = [k for k in ("MPESA_CONSUMER_KEY", "MPESA_CONSUMER_SECRET", "MPESA_PASSKEY", "FIREBASE_PROJECT_ID",
                           "FIREBASE_API_KEY", "MINTER_PRIVATE_KEY") if not keep(k)]
    print(f"Wrote {OUT}")
    print(f"API address:  https://{api_domain}")
    print("Demo phone logins (share these; codes never change):")
    for phone, code in demo.items():
        print(f"  {phone}  code {code}")
    if missing:
        print("Not found in your local .env — fill these in before starting:", ", ".join(missing))


if __name__ == "__main__":
    main()
